"""Engine metrics — constraint engine vs the golden dataset (2,313 rows).

Engine-only: uses each row's *given* intent, so this isolates constraint-engine
correctness from intent classification. Run intent classification metrics
separately (run_classifier.py).

Usage:  py -3 guardrail/evals/run_golden.py [--dataset PATH] [--md OUT.md]
"""
from __future__ import annotations

import argparse
import json
import sys
import time
from collections import Counter, defaultdict
from pathlib import Path

_REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(_REPO / "guardrail"))

from policy import PolicyEngine, RuleSet, VehicleState  # noqa: E402
from policy.state import REQUEST_PARAMS  # noqa: E402

_DEFAULT_DATASET = _REPO / "golden-dataset/driver-constraints/output/pipeline/dataset.jsonl"


def load_rows(path: Path) -> list[dict]:
    with path.open(encoding="utf-8") as fh:
        return [json.loads(line) for line in fh if line.strip()]


def split_state(vehicle_state: dict) -> tuple[dict, dict]:
    """-> (state overrides, request params)"""
    params = {k: v for k, v in vehicle_state.items() if k in REQUEST_PARAMS}
    state = {k: v for k, v in vehicle_state.items() if k not in REQUEST_PARAMS}
    return state, params


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dataset", type=Path, default=_DEFAULT_DATASET)
    ap.add_argument("--md", type=Path, default=_REPO / "docs/metrics/engine.md")
    args = ap.parse_args()

    ruleset = RuleSet.load()
    engine = PolicyEngine(ruleset)
    mode_by_rule = {r.rule_id: r.check_mode for r in ruleset.all()}
    rows = load_rows(args.dataset)

    total = len(rows)
    correct = 0
    fail_closed = 0
    per_intent: dict[str, list[int]] = defaultdict(lambda: [0, 0])          # [correct, total]
    per_expected: dict[str, list[int]] = defaultdict(lambda: [0, 0])
    confusion: Counter = Counter()                                          # (expected, got)
    mismatches: list[dict] = []
    latencies: list[float] = []

    for row in rows:
        expected = row["expected_outcome"]
        state_over, params = split_state(row.get("vehicle_state") or {})
        check_mode = mode_by_rule.get(row["rule_id"], "gate")
        try:
            state = VehicleState.from_partial(state_over)
        except ValueError as exc:
            mismatches.append({**_slim(row), "got": f"STATE_ERROR: {exc}"})
            confusion[(expected, "STATE_ERROR")] += 1
            per_intent[row["intent"]][1] += 1
            per_expected[expected][1] += 1
            continue

        t0 = time.perf_counter()
        decision = engine.evaluate(
            row["intent"], state, check_mode=check_mode, request_params=params
        )
        latencies.append((time.perf_counter() - t0) * 1000.0)

        got = decision.outcome or f"FAIL_CLOSED:{decision.reason_code}"
        ok = decision.outcome == expected
        correct += ok
        if decision.is_fail_closed:
            fail_closed += 1
        per_intent[row["intent"]][0] += ok
        per_intent[row["intent"]][1] += 1
        per_expected[expected][0] += ok
        per_expected[expected][1] += 1
        confusion[(expected, decision.outcome or "FAIL_CLOSED")] += 1
        if not ok:
            mismatches.append({
                **_slim(row),
                "got": got,
                "rule_id_hit": decision.rule_id,
                "detail": decision.error or "",
            })

    latencies.sort()
    p = lambda q: latencies[min(len(latencies) - 1, int(len(latencies) * q))] if latencies else 0.0

    lines: list[str] = []
    w = lines.append
    w("# Engine metrics — constraint engine vs golden dataset")
    w("")
    w(f"> Generated by `guardrail/evals/run_golden.py` · {time.strftime('%Y-%m-%d %H:%M')}")
    w(f"> Dataset: `{args.dataset.relative_to(_REPO)}` ({total} rows) · "
      f"policy_checksum `{ruleset.policy_checksum[:23]}…`")
    w("> Engine-only: uses each row's given intent (isolates constraint engine from classification).")
    w("")
    w("## Headline")
    w("")
    w(f"| metric | value |")
    w(f"|---|---|")
    w(f"| rows | {total} |")
    w(f"| **outcome accuracy** | **{correct}/{total} = {correct/total:.1%}** |")
    w(f"| fail-closed (no outcome) | {fail_closed} ({fail_closed/total:.1%}) |")
    w(f"| engine latency p50 / p95 / p99 | {p(.5):.3f} / {p(.95):.3f} / {p(.99):.3f} ms |")
    w("")
    w("## Accuracy by expected outcome")
    w("")
    w("| expected | correct | total | acc |")
    w("|---|---|---|---|")
    for oc in sorted(per_expected):
        c, t = per_expected[oc]
        w(f"| {oc} | {c} | {t} | {c/t:.1%} |")
    w("")
    w("## Confusion (expected → got), mismatches only")
    w("")
    w("| expected | got | n |")
    w("|---|---|---|")
    for (exp, got), n in confusion.most_common():
        if exp != got:
            w(f"| {exp} | {got} | {n} |")
    w("")
    w("## Worst intents")
    w("")
    w("| intent | correct | total | acc |")
    w("|---|---|---|---|")
    for intent in sorted(per_intent, key=lambda k: per_intent[k][0] / max(1, per_intent[k][1])):
        c, t = per_intent[intent]
        if c < t:
            w(f"| `{intent}` | {c} | {t} | {c/t:.1%} |")
    w("")
    w(f"## Mismatches ({len(mismatches)}) — first 60")
    w("")
    w("| sample_id | intent | rule | expected | got | detail |")
    w("|---|---|---|---|---|---|")
    for m in mismatches[:60]:
        w(f"| {m['sample_id']} | `{m['intent']}` | {m['rule_id']} | {m['expected']} | "
          f"{m['got']} | {m.get('detail','')[:70]} |")

    lines.append("")
    lines.append("---")
    lines.append("> Generated — overwritten on each run. Interpretation and context:")
    lines.append("> `docs/METRICS.md`.")
    args.md.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines[:22]))
    print(f"\n... full report: {args.md.relative_to(_REPO)}  ({len(mismatches)} mismatches)")
    return 0


def _slim(row: dict) -> dict:
    return {k: row[k] for k in ("sample_id", "rule_id", "intent", "expected_outcome")} | {
        "expected": row["expected_outcome"]
    }


if __name__ == "__main__":
    raise SystemExit(main())
