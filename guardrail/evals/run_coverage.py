"""Automated coverage report — writes ``docs/COVERAGE.md``.

Checks that the policy workbook, the tool->intent map and the outcome set all
line up, and that every workbook intent is reachable. Exits non-zero on any
mismatch.

Run:  py -3 guardrail/evals/run_coverage.py
"""
from __future__ import annotations

import sys
from datetime import date
from pathlib import Path

_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(_ROOT))

from policy import RuleSet  # noqa: E402
from service.tool_map import DEFAULT_MAPPER, DEFAULT_MAPPING_RULES  # noqa: E402

_OUT = _ROOT.parent / "docs" / "COVERAGE.md"
_SEVEN = ("ALLOW", "BLOCK_UNSAFE", "BLOCK_UNAVAILABLE", "CONFIRM", "NOT_VOICE_ACTIONABLE", "ANSWER", "UNKNOWN")


def build_report() -> tuple[str, bool]:
    rs = RuleSet.load()
    rules = rs.all()
    workbook_intents = set(rs.intents)
    gate = sum(r.check_mode == "gate" for r in rules)
    monitor = [r for r in rules if r.check_mode == "monitor"]
    outcomes_present = {r.outcome for r in rules}
    mapped_intents = DEFAULT_MAPPER.intents

    unreachable = sorted(workbook_intents - mapped_intents)
    mapped_not_in_workbook = sorted(mapped_intents - workbook_intents)
    missing_outcomes = [o for o in _SEVEN if o not in outcomes_present]

    ok = (
        len(rules) == 109 and len(workbook_intents) == 53 and gate == 104
        and len(monitor) == 5 and not unreachable and not missing_outcomes
    )

    lines = [
        "# Coverage report",
        "",
        f"Generated by `guardrail/evals/run_coverage.py` · {date.today().isoformat()}",
        f"**Result: {'PASS ✅' if ok else 'FAIL ❌'}**",
        "",
        "## Policy workbook",
        "",
        "| | expected | actual | |",
        "|---|---|---|---|",
        f"| rules | 109 | {len(rules)} | {'✅' if len(rules)==109 else '❌'} |",
        f"| intents | 53 | {len(workbook_intents)} | {'✅' if len(workbook_intents)==53 else '❌'} |",
        f"| gate rules | 104 | {gate} | {'✅' if gate==104 else '❌'} |",
        f"| monitor rules | 5 | {len(monitor)} | {'✅' if len(monitor)==5 else '❌'} |",
        f"| policy_checksum | — | `{rs.policy_checksum}` | |",
        "",
        "`RuleSet.load()` fails closed if any count is off or any condition won't parse.",
        "",
        "## Intent coverage via the tool→intent map",
        "",
        f"- The copied map: **{len(DEFAULT_MAPPING_RULES)} rows** → **{len(mapped_intents)} intents**.",
        f"- Workbook intents **not** reachable through the map: {unreachable or 'none ✅'}",
        f"- Intents mapped but **not** in the workbook: {mapped_not_in_workbook or 'none'}",
    ]
    if mapped_not_in_workbook:
        lines.append(
            "  - `turnon_LKA` — the map reaches "
            "`control_driver_assistance/activate/lane_keeping_assist` but the workbook only has "
            "`turnoff_LKA`, so the service returns a typed error (never `ALLOW`). Needs a workbook "
            "rule for this intent, or removal from the map."
        )
    lines += [
        "",
        "## Outcomes",
        "",
        f"- Present in the workbook: {sorted(outcomes_present)}",
        f"- Missing: {missing_outcomes or 'none ✅'}",
        "- Routing evidence for all 7 across the 2,313-row labelled dataset: `run_golden.py` (100%).",
        "",
        "## Monitor rules (each has a test scenario in `guardrail/tests/test_monitor.py`)",
        "",
        "| rule_id | intent | outcome | condition |",
        "|---|---|---|---|",
    ]
    for r in sorted(monitor, key=lambda x: x.rule_id):
        lines.append(f"| {r.rule_id} | {r.intent} | {r.outcome} | `{r.raw_condition}` |")
    lines += [
        "",
        "## End-to-end demo",
        "",
        "`py -3 run_demo.py` — ALLOW / BLOCK_UNSAFE / CONFIRM(+confirm) / ANSWER / MONITOR, each "
        "printing the full guardrail trace + latency.",
        "",
        "> Caveats: the labelled dataset is `reviewed = 0` (matches-the-label, not independently "
        "audited); `_STATE_DEFAULTS` is an assumption. This is a simulation.",
        "",
    ]
    return "\n".join(lines), ok


def main() -> int:
    report, ok = build_report()
    _OUT.write_text(report, encoding="utf-8")
    print(report)
    print(f"\n-> {_OUT}")
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
